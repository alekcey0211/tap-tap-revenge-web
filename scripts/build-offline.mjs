import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = new URL('../dist/', import.meta.url);
const hash = data => createHash('sha256').update(data).digest('hex');
const version = (await readFile(new URL('app.js', root), 'utf8')).match(/APP_VERSION = '([^']+)'/)[1];
const catalog = JSON.parse(await readFile(new URL('assets/catalog.json', root)));
async function entry(path) {
  const bytes = await readFile(new URL(path, root));
  return { path, hash: hash(bytes), bytes: bytes.length };
}
async function walk(path = '') {
  const result = [];
  for (const item of await readdir(new URL(path || '.', root), { withFileTypes: true })) {
    if (item.isDirectory()) result.push(...await walk(path + item.name + '/'));
    else result.push(path + item.name);
  }
  return result.sort();
}
const shell = await Promise.all((await walk()).filter(path => !['sw.js', 'offline-assets.js'].includes(path)
  && (!path.startsWith('assets/tracks/') || path.endsWith('/artwork.png'))).map(entry));
const tracks = {};
for (const song of catalog) {
  const base = `assets/tracks/${song.id}/`;
  const paths = ['audio.m4a', ...Object.keys(song.levels).map(level => level + '.json')];
  if (!song.tutorial) paths.push('artwork.png');
  const files = await Promise.all(paths.map(path => entry(base + path)));
  tracks[song.id] = { files, revision: hash(JSON.stringify(files)).slice(0, 16) };
}
const worker = await readFile(new URL('sw.js', root), 'utf8');
const data = { version, revision: hash(JSON.stringify(shell) + worker).slice(0, 16), shell, tracks };
const output = '// Generated by node scripts/build-offline.mjs. Do not edit.\nself.OFFLINE_ASSETS = ' + JSON.stringify(data, null, 2) + ';\n';
const target = new URL('offline-assets.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Offline manifest is stale: run node scripts/build-offline.mjs');
} else await writeFile(target, output);
console.log(`Offline manifest ${version}: ${shell.length} shell files, ${Object.keys(tracks).length} tracks (${fileURLToPath(target)})`);
