import { cp, readFile, writeFile, readdir, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Publish the accepted Babylon build at / and keep existing /prototype/ installs.
// dist remains the shared application source + the reproducible prototype build.
const source = new URL('../dist/prototype/', import.meta.url);
const target = new URL('../release/', import.meta.url);
const { version } = JSON.parse(await readFile(new URL('../package.json', import.meta.url)));
const hash = data => createHash('sha256').update(data).digest('hex');
function replace(text, from, to) {
  if (!text.includes(from)) throw new Error(`Release input changed: ${from}`);
  return text.replaceAll(from, to);
}
await rm(target, { recursive: true, force: true });
await cp(source, target, { recursive: true });
for (const path of ['app.js', 'game-bootstrap.js', 'index.html']) {
  let text = await readFile(new URL(path, target), 'utf8');
  text = path === 'index.html' ? replace(text, 'v=0.6.1', `v=${version}`)
    : replace(text, '0.6.1-babylon', version).replaceAll('v=0.6.1', `v=${version}`);
  if (path === 'index.html') {
    text = replace(text, 'TAPBEAT · Stage Lab', 'Tapbeat');
    text = replace(text, 'Тапай в бит · STAGE LAB', 'Тапай в бит');
    text = replace(text, '<p class="babylon-badge">STAGE LAB · отдельные настройки, рекорды и офлайн-треки</p>', '');
    text = replace(text, '<a href="../#/">Рабочая версия</a>', '');
    text = replace(text, '<a href="../#/">Рабочая игра</a>', '');
    text = replace(text, 'перезагрузи прототип', 'перезагрузи игру');
  }
  await writeFile(new URL(path, target), text);
}
const manifestPath = new URL('manifest.webmanifest', target);
const manifest = JSON.parse(await readFile(manifestPath));
manifest.name = 'Tapbeat'; // Keep id, scope and start_url: existing installed PWA identity.
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
// Existing prototype saves win. When absent, retain the old stable audio/settings,
// without comparing records from differently numbered charts. Old keys stay intact.
const storagePath = new URL('storage.js', target);
let storage = await readFile(storagePath, 'utf8');
storage = replace(storage, '  let settings = defaults;\n', `  let settings = defaults;
  try { settings = settingsFrom(JSON.parse(storage.getItem('ttr-web-settings') || '{}'), settings); } catch {}
  try { const previous = storage.getItem('ttr-web-save-v1'); if (previous) settings = parseProgress(previous).settings; } catch {}
`);
storage = replace(storage, "storage.getItem('ttr-babylon-settings') || '{}'), defaults)", "storage.getItem('ttr-babylon-settings') || '{}'), settings)");
await writeFile(storagePath, storage);
const workerPath = new URL('sw.js', target);
let worker = await readFile(workerPath, 'utf8');
worker = replace(worker, 'const keep = new Set([shellName, ...Object.keys(tracks).map(trackName)]);',
  'const retained = await migrateSelectedTracks();\n  const keep = new Set([shellName, ...Object.keys(tracks).map(trackName), ...retained]);');
worker += '\n' + await readFile(new URL('release/migrate-tracks.js', import.meta.url), 'utf8');
await writeFile(workerPath, worker);
const original = JSON.parse((await readFile(new URL('offline-assets.js', source), 'utf8')).split(' = ')[1].replace(/;\s*$/, ''));
const shell = await Promise.all(original.shell.map(async ({ path }) => {
  const bytes = await readFile(new URL(path, target)); return { path, hash: hash(bytes), bytes: bytes.length };
}));
const assets = { ...original, version, revision: hash(JSON.stringify(shell) + worker).slice(0, 16), shell };
const offline = data => '// Generated by scripts/build-release.mjs. Do not edit.\nself.OFFLINE_ASSETS = ' + JSON.stringify(data, null, 2) + ';\n';
await writeFile(new URL('offline-assets.js', target), offline(assets));
// Copy before creating the nested directory to avoid recursive self-copy.
const mirror = new URL('prototype/', target);
for (const entry of await readdir(target)) await cp(new URL(entry, target), new URL(entry, mirror), { recursive: true });
await writeFile(new URL('offline-assets.js', target), offline({ ...assets, previousTrackScopes: ['prototype/'] }));
console.log(`Tapbeat ${version}: stable root + compatible /prototype/ URL, ${shell.length} shell assets.`);
